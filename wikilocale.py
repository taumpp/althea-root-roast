BONUS_APPLIES = {'monster_bonus': 'ATTBONUS_MONSTER', 'boss_bonus': 'ATTBONUS_BOSS', 'boss_resist': 'RESIST_BOSS', 'animal_bonus': 'ATTBONUS_ANIMAL', 'orc_bonus': 'ATTBONUS_ORC', 'undead_bonus': 'ATTBONUS_UNDEAD', 'devil_bonus': 'ATTBONUS_DEVIL', 'milgyo_bonus': 'ATTBONUS_MILGYO', 'lightning_resist': 'RESIST_ELEC', 'fire_resist': 'RESIST_FIRE', 'ice_resist': 'RESIST_ICE', 'wind_resist': 'RESIST_WIND', 'earth_resist': 'RESIST_EARTH', 'dark_resist': 'RESIST_DARK', 'base_attack': 'ATT_GRADE_BONUS', 'base_magic_attack': 'MAGIC_ATT_GRADE', 'base_defense': 'DEF_GRADE_BONUS', 'base_magic_defense': 'MAGIC_DEF_GRADE'}


def BonusApply(key):
    import item
    symbol = BONUS_APPLIES.get(key)
    return getattr(item, 'APPLY_'+symbol, None) if symbol else None


def BonusName(kind):
    import bonuslabels
    import uiToolTip
    if kind is None:
        return ''
    description = bonuslabels.Describe(uiToolTip.GET_AFFECT_STRING, kind)
    return description[0] if description else ''


def Text(key):
    if key.startswith('rarity_grade_') and key.rsplit('_',1)[-1].isdigit():
        import uiToolTip
        grade = int(key.rsplit('_',1)[-1])
        if 0 <= grade < len(uiToolTip.RARITY_GRADE_NAMES):
            return uiToolTip.RARITY_GRADE_NAMES[grade]
    if key in BONUS_APPLIES:
        return BonusName(BonusApply(key))
    return TEXT.get(key, key)
